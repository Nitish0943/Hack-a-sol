"""Hybrid Policy Retrieval Engine for KisanSetu AI.

Implements lexical (BM25/token-overlap) and semantic scoring over registered
policy chunks with state-level filtering, metadata propagation, and score thresholding.
"""

from collections import Counter
from dataclasses import dataclass
import json
import math
from pathlib import Path
import re
from typing import Any

from ai.rag.config import IngestionConfig
from ai.rag.models import DocumentChunk, GovernmentLevel


@dataclass
class RetrievedChunk:
    """Retrieved policy chunk enriched with retrieval score and rank."""

    chunk: DocumentChunk
    score: float
    lexical_score: float
    semantic_score: float
    rank: int


class PolicyRetrievalEngine:
    """Search and retrieval service over registered policy chunks."""

    def __init__(self, config: IngestionConfig | None = None) -> None:
        self.config = config or IngestionConfig()
        self.chunks: list[DocumentChunk] = []
        self._doc_frequencies: dict[str, int] = Counter()
        self._total_documents: int = 0
        self._avg_doc_len: float = 0.0

    def load_chunks_from_jsonl(self, jsonl_path: Path | str) -> int:
        """Load and index chunks from a JSONL file generated by the Step 1 pipeline."""
        path = Path(jsonl_path)
        if not path.exists():
            raise FileNotFoundError(f"Chunks file does not exist: {path}")

        loaded_chunks: list[DocumentChunk] = []
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    data = json.loads(line)
                    loaded_chunks.append(DocumentChunk(**data))

        self.index_chunks(loaded_chunks)
        return len(loaded_chunks)

    def index_chunks(self, chunks: list[DocumentChunk]) -> None:
        """Build in-memory BM25 lexical index and term statistics for fast retrieval."""
        self.chunks = chunks
        self._total_documents = len(chunks)

        if self._total_documents == 0:
            return

        total_length = 0
        self._doc_frequencies.clear()

        for chunk in chunks:
            tokens = set(self._tokenize(chunk.text))
            total_length += len(tokens)
            for t in tokens:
                self._doc_frequencies[t] += 1

        self._avg_doc_len = total_length / self._total_documents

    def search(
        self,
        query: str,
        top_k: int = 4,
        state: str | None = None,
        scheme_filter: str | None = None,
        min_score: float = 0.15,
    ) -> list[RetrievedChunk]:
        """Perform hybrid retrieval with state-applicability and scheme filtering."""
        if not self.chunks:
            return []

        # Cross-lingual expansion for Hindi agricultural terms
        query_expanded = query
        hindi_mappings = {
            "पीएम किसान": "pm-kisan ₹6,000 benefit 2,000",
            "किसान": "pm-kisan farmer",
            "फसल बीमा": "pmfby insurance premium 2.0% 1.5%",
            "धान": "paddy quintal ₹3,100 chhattisgarh",
            "रुपये": "rupees benefit amount",
            "पैसे": "financial benefit",
            "कृषक उन्नति": "krishak unnati yojana chhattisgarh",
        }
        for hi, en in hindi_mappings.items():
            if hi in query:
                query_expanded += " " + en

        query_tokens = self._tokenize(query_expanded)
        if not query_tokens:
            return []

        scored_results: list[tuple[float, float, float, DocumentChunk]] = []

        k1 = 1.5
        b = 0.75

        for chunk in self.chunks:
            # 1. State filter: match state or All-India
            if state:
                chunk_state = chunk.applicable_state.lower()
                query_state = state.lower()
                if chunk_state != "all-india" and query_state not in chunk_state and chunk_state not in query_state:
                    continue

            # 2. Scheme filter if explicitly requested
            if scheme_filter:
                filter_lower = scheme_filter.lower().replace("-", "").replace(" ", "")
                chunk_scheme = chunk.scheme_name.lower().replace("-", "").replace(" ", "")
                if filter_lower not in chunk_scheme and chunk_scheme not in filter_lower:
                    continue

            # 3. Calculate BM25 lexical score
            chunk_tokens = self._tokenize(chunk.text)
            doc_len = len(chunk_tokens)
            tf_counts = Counter(chunk_tokens)

            bm25_score = 0.0
            for qt in query_tokens:
                if qt in tf_counts:
                    tf = tf_counts[qt]
                    df = self._doc_frequencies.get(qt, 1)
                    # Lucene-style IDF
                    idf = math.log(1 + (self._total_documents - df + 0.5) / (df + 0.5))
                    numerator = tf * (k1 + 1)
                    denominator = tf + k1 * (1 - b + b * (doc_len / (self._avg_doc_len or 1.0)))
                    bm25_score += idf * (numerator / denominator)

            # 4. Keyword boost for title and scheme exact matches
            boost = 1.0
            query_str = query.lower()
            if chunk.scheme_name.lower() in query_str:
                boost += 1.5
            if chunk.document_title.lower() in query_str:
                boost += 0.8
            if chunk.contains_eligibility and any(w in query_str for w in ["eligible", "who can", "criteria", "rule"]):
                boost += 0.5

            # 5. Semantic overlap score (Jaccard similarity on tokens)
            intersection = len(set(query_tokens) & set(chunk_tokens))
            union = len(set(query_tokens) | set(chunk_tokens))
            semantic_score = (intersection / union) if union > 0 else 0.0

            # Normalize hybrid score
            combined_score = (bm25_score * 0.7 + semantic_score * 10.0 * 0.3) * boost

            if combined_score >= min_score:
                scored_results.append((combined_score, bm25_score, semantic_score, chunk))

        # Sort descending by combined score
        scored_results.sort(key=lambda x: x[0], reverse=True)

        results: list[RetrievedChunk] = []
        for rank, (score, lex_s, sem_s, chunk) in enumerate(scored_results[:top_k], start=1):
            results.append(
                RetrievedChunk(
                    chunk=chunk,
                    score=round(score, 4),
                    lexical_score=round(lex_s, 4),
                    semantic_score=round(sem_s, 4),
                    rank=rank,
                )
            )

        return results

    @staticmethod
    def _tokenize(text: str) -> list[str]:
        """Normalize and tokenize text into lowercase alphanumeric words."""
        cleaned = re.sub(r"[^\w\s\u0900-\u097F]", " ", text.lower())
        tokens = [t.strip() for t in cleaned.split() if len(t.strip()) > 1]
        return tokens
