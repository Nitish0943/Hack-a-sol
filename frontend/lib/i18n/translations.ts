type TranslationEntry = (typeof entries)[number];
type Dictionary = Record<string, { hi: string; hne: string }>;

export const dictionary: Dictionary = Object.fromEntries(
  entries.map(([english, hindi, chhattisgarhi]: TranslationEntry) => [
    english.toLowerCase().trim(),
    { hi: hindi, hne: chhattisgarhi },
  ]),
);

// Sorted entries by length descending for phrase replacement
const sortedPhraseEntries = [...entries].sort((a, b) => b[0].length - a[0].length);

export function isLanguage(value: string | null): value is Language {
  return value !== null && languages.some((language) => language === value);
}

function stripPunctuation(str: string): { prefix: string; core: string; suffix: string } {
  const match = str.match(/^([^a-zA-Z0-9\u0900-\u097F]*)(.*?)([^a-zA-Z0-9\u0900-\u097F]*)$/);
  if (!match) return { prefix: "", core: str, suffix: "" };
  return {
    prefix: match[1] || "",
    core: match[2] || "",
    suffix: match[3] || "",
  };
}

function translatePattern(text: string, language: Language): string | null {
  if (language === "en") return null;

  const snakeCaseMatch = text.match(/^[a-z0-9]+(?:_[a-z0-9]+)+$/i);
  if (snakeCaseMatch) {
    const phrase = text.replace(/_/g, " ");
    const translated = translateText(phrase, language);
    if (translated !== phrase) return translated;
  }

  const namasteMatch = text.match(/^(?:Namaste|Welcome)[,\s]+([A-Za-z\s]+)$/i);
  if (namasteMatch) {
    const name = namasteMatch[1].trim();
    return language === "hi" ? `नमस्ते, ${name}` : `जोहार, ${name}`;
  }

  const welcomeBackMatch = text.match(/^Welcome back[,\s]+([A-Za-z\s]+)$/i);
  if (welcomeBackMatch) {
    const name = welcomeBackMatch[1].trim();
    return language === "hi" ? `वापस स्वागत है, ${name}` : `फेर ले स्वागत हे, ${name}`;
  }

  const verifiedMatch = text.match(/^Last verified:\s*([0-9\-\/A-Za-z]+)$/i);
  if (verifiedMatch) {
    const date = verifiedMatch[1];
    return language === "hi" ? `अंतिम सत्यापन: ${date}` : `आखिरी जांच: ${date}`;
  }

  const updatedMatch = text.match(/^Updated\s+(.+)$/i);
  if (updatedMatch) {
    const time = updatedMatch[1].trim();
    const timeTrans = translateText(time, language);
    return language === "hi" ? `अपडेट किया गया ${timeTrans}` : `अपडेट करे गे ${timeTrans}`;
  }

  const minMatch = text.match(/^(\d+)\s*(?:min|mins|minute|minutes)\s+ago$/i);
  if (minMatch) {
    const n = minMatch[1];
    return language === "hi" ? `${n} मिनट पहले` : `${n} मिनट पहिले`;
  }

  const hrMatch = text.match(/^(\d+)\s*(?:hr|hrs|hour|hours)\s+ago$/i);
  if (hrMatch) {
    const n = hrMatch[1];
    return language === "hi" ? `${n} घंटे पहले` : `${n} घंटा पहिले`;
  }

  const dayMatch = text.match(/^(\d+)\s*(?:day|days)\s+ago$/i);
  if (dayMatch) {
    const n = dayMatch[1];
    return language === "hi" ? `${n} दिन पहले` : `${n} दिन पहिले`;
  }

  const daysMatch = text.match(/^(\d+)\s+days?$/i);
  if (daysMatch) {
    return `${daysMatch[1]} दिन`;
  }

  const dateMatch = text.match(
    /^(\d{1,2})\s+(Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|Jul(?:y)?|Aug(?:ust)?|Sep(?:tember)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?)\s+(\d{4})(?:,\s*(\d{1,2}:\d{2})\s*(AM|PM))?$/i,
  );
  if (dateMatch) {
    const months: Record<string, string> = {
      jan: "जनवरी",
      feb: "फ़रवरी",
      mar: "मार्च",
      apr: "अप्रैल",
      may: "मई",
      jun: "जून",
      jul: "जुलाई",
      aug: "अगस्त",
      sep: "सितंबर",
      oct: "अक्टूबर",
      nov: "नवंबर",
      dec: "दिसंबर",
    };
    const month = months[dateMatch[2].slice(0, 3).toLowerCase()];
    const time = dateMatch[4]
      ? `, ${dateMatch[5].toUpperCase() === "AM" ? "सुबह" : "शाम"} ${dateMatch[4]}`
      : "";
    return `${dateMatch[1]} ${month} ${dateMatch[3]}${time}`;
  }

  const targetDateMatch = text.match(
    /^Target:\s*(\d{1,2}\s+(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\s+\d{4})$/i,
  );
  if (targetDateMatch) {
    return `लक्ष्य: ${translateText(targetDateMatch[1], language)}`;
  }

  const upToMatch = text.match(/^Up to\s*(₹[\d,]+.*)$/i);
  if (upToMatch) {
    const amt = upToMatch[1];
    return `${amt} तक`;
  }

  const yrMatch = text.match(/^(₹[\d,]+)\s*\/\s*(?:yr|year)$/i);
  if (yrMatch) {
    const amt = yrMatch[1];
    return language === "hi" ? `${amt} / वर्ष` : `${amt} / साल`;
  }

  const moMatch = text.match(/^(₹[\d,]+)\s*\/\s*(?:mo|month)$/i);
  if (moMatch) {
    const amt = moMatch[1];
    return `${amt} / महीना`;
  }

  const acreMatch = text.match(/^([\d\.]+)\s*(?:acres|acre)$/i);
  if (acreMatch) {
    const n = acreMatch[1];
    return `${n} एकड़`;
  }

  const portalMatch = text.match(/^(Farmer|Officer|Administrator)\s+Portal$/i);
  if (portalMatch) {
    const roleKey = portalMatch[1].toLowerCase();
    const roleTrans = dictionary[roleKey]?.[language] || portalMatch[1];
    return `${roleTrans} पोर्टल`;
  }

  const workspaceMatch = text.match(/^(Farmer|Officer|Administrator)\s+workspace$/i);
  if (workspaceMatch) {
    const roleKey = workspaceMatch[1].toLowerCase();
    const roleTrans = dictionary[roleKey]?.[language] || portalMatch?.[1] || "";
    return language === "hi" ? `${roleTrans} कार्यक्षेत्र` : `${roleTrans} काम के जगह`;
  }

  const placeMatch = text.match(/^(.+), (.+) is an active notified agricultural implementation zone\.$/);
  if (placeMatch) {
    const place = `${translateText(placeMatch[1], language)}, ${translateText(placeMatch[2], language)}`;
    return language === "hi"
      ? `${place} एक अधिसूचित सक्रिय कृषि कार्यान्वयन क्षेत्र है।`
      : `${place} एक अधिसूचित चालू खेती इलाका हे।`;
  }

  const landMatch = text.match(/^Declared ([\d.]+) acres qualifies for this scheme(?: \((Verified via document|Document verification required)\))?\.$/);
  if (landMatch) {
    const qualification = landMatch[2] === "Verified via document"
      ? (language === "hi" ? "दस्तावेज़ से सत्यापित" : "कागज ले जांचे गे")
      : landMatch[2]
        ? (language === "hi" ? "दस्तावेज़ सत्यापन आवश्यक" : "कागज जांच जरूरी हे")
        : "";
    const suffix = qualification ? ` (${qualification})` : "";
    return language === "hi"
      ? `घोषित ${landMatch[1]} एकड़ भूमि इस योजना के लिए पात्र है${suffix}।`
      : `घोषित ${landMatch[1]} एकड़ जमीन ए योजना बर पात्र हे${suffix}।`;
  }

  const landThresholdMatch = text.match(/^Landholding of ([\d.]+) acres does not meet threshold\.$/);
  if (landThresholdMatch) {
    return language === "hi"
      ? `${landThresholdMatch[1]} एकड़ की भूमि निर्धारित सीमा पूरी नहीं करती।`
      : `${landThresholdMatch[1]} एकड़ जमीन तय सीमा म नइ आवय।`;
  }

  const cultivatorMatch = text.match(/^(.+) is an eligible category for (.+)\.$/);
  if (cultivatorMatch) {
    const cultivator = translateText(cultivatorMatch[1], language);
    const scheme = translateText(cultivatorMatch[2], language);
    return language === "hi"
      ? `${cultivator}, ${scheme} के लिए पात्र श्रेणी है।`
      : `${cultivator}, ${scheme} बर पात्र किसम हे।`;
  }

  const cropMatch = text.match(/^(.+) is an officially notified crop for season 2026\.$/);
  if (cropMatch) {
    const crop = translateText(cropMatch[1], language);
    return language === "hi"
      ? `${crop} 2026 के मौसम के लिए आधिकारिक रूप से अधिसूचित फसल है।`
      : `${crop} 2026 सीजन बर आधिकारिक रूप ले अधिसूचित फसल हे।`;
  }

  const cropUnavailableMatch = text.match(/^(.+) is not notified for subsidy under this specific scheme code\.$/);
  if (cropUnavailableMatch) {
    const crop = translateText(cropUnavailableMatch[1], language);
    return language === "hi"
      ? `${crop} इस योजना कोड के तहत सब्सिडी के लिए अधिसूचित नहीं है।`
      : `${crop} ए योजना कोड म सहायता बर अधिसूचित नइ हे।`;
  }

  const farmerCategoryMatch = text.match(/^(.+) is currently not recognized under this scheme guideline without an authorized tenancy deed\.$/);
  if (farmerCategoryMatch) {
    const category = translateText(farmerCategoryMatch[1], language);
    return language === "hi"
      ? `${category} को अधिकृत किरायेदारी दस्तावेज़ के बिना इस योजना के नियमों में मान्यता नहीं है।`
      : `${category} ला अधिकृत किरायेदारी कागज बिना ए योजना के नियम म मान्यता नइ हे।`;
  }

  const effectiveInterestMatch = text.match(/^Effective Interest:\s*([\d.]+)%\s*p\.a\.$/i);
  if (effectiveInterestMatch) {
    return language === "hi"
      ? `प्रभावी ब्याज: ${effectiveInterestMatch[1]}% प्रति वर्ष`
      : `असल बियाज: ${effectiveInterestMatch[1]}% सालाना`;
  }

  const subsidyMatch = text.match(/^Government Subsidy:\s*(₹[\d,]+)$/i);
  if (subsidyMatch) {
    return language === "hi"
      ? `सरकारी सब्सिडी: ${subsidyMatch[1]}`
      : `सरकारी सहायता: ${subsidyMatch[1]}`;
  }

  const tenureMatch = text.match(/^(\d+)\s+months tenure$/i);
  if (tenureMatch) {
    return language === "hi"
      ? `${tenureMatch[1]} महीने की अवधि`
      : `${tenureMatch[1]} महीना के मियाद`;
  }

  const interestCalculationMatch = text.match(
    /^Calculated using standard Kisan Credit Card 3% prompt-repayment subvention rules\. Normal interest = (₹[\d,]+) \(at ([\d.]+)%\)\. Subvention credit = (₹[\d,]+) \(at ([\d.]+)%\)\. Net farmer interest payable = (₹[\d,]+)\.$/,
  );
  if (interestCalculationMatch) {
    const [, normalInterest, normalRate, subvention, subventionRate, netInterest] = interestCalculationMatch;
    return language === "hi"
      ? `किसान क्रेडिट कार्ड के 3% समय पर पुनर्भुगतान ब्याज सहायता नियमों से गणना। सामान्य ब्याज = ${normalInterest} (${normalRate}% पर)। ब्याज सहायता = ${subvention} (${subventionRate}% पर)। किसान को देय शुद्ध ब्याज = ${netInterest}।`
      : `किसान क्रेडिट कार्ड के 3% समय म कर्जा लौटाय के मदद नियम ले हिसाब। सामान्य बियाज = ${normalInterest} (${normalRate}% पर)। बियाज मदद = ${subvention} (${subventionRate}% पर)। किसान ला देय कुल बियाज = ${netInterest}।`;
  }

  const equipmentCalculationMatch = text.match(
    /^Equipment assistance calculated as min\(Project Cost × ([\d.]+)%, Max Cap (₹[\d,]+)\)\. Gross subsidy calculated: (₹[\d,]+); Effective applied grant: (₹[\d,]+)\.$/,
  );
  if (equipmentCalculationMatch) {
    const [, percent, maxCap, gross, grant] = equipmentCalculationMatch;
    return language === "hi"
      ? `उपकरण सहायता की गणना परियोजना लागत × ${percent}% या अधिकतम सीमा ${maxCap}, इनमें जो कम हो, उसके अनुसार हुई। कुल सब्सिडी: ${gross}; लागू अनुदान: ${grant}।`
      : `औजार के मदद परियोजना लागत × ${percent}% या अधिकतम सीमा ${maxCap}, जेमे कम हो, ओखर मुताबिक निकले हे। कुल सहायता: ${gross}; लागू अनुदान: ${grant}।`;
  }

  return null;
}

export function translateText(value: string, language: Language): string {
  const source = getEnglishSource(value);
  if (language === "en" || !source || !source.trim()) return source;

  // Don't translate URLs, code snippets, or pure numbers
  if (/^https?:\/\//i.test(source.trim()) || /^[\d\s,.\-%₹$]+$/.test(source.trim())) {
    return source;
  }

  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const trimmed = source.trim();

  // 1. Exact match
  const exactKey = trimmed.replace(/\s+/g, " ").toLowerCase();
  const exact = dictionary[exactKey];
  if (exact) {
    return `${leading}${exact[language]}${trailing}`;
  }

  // 2. Strip punctuation match (e.g. "Full name *", "Category:", "(Optional)", "Need help?")
  const { prefix, core, suffix } = stripPunctuation(trimmed);
  if (core && core !== trimmed) {
    const coreKey = core.replace(/\s+/g, " ").trim().toLowerCase();
    const coreMatch = dictionary[coreKey];
    if (coreMatch) {
      return `${leading}${prefix}${coreMatch[language]}${suffix}${trailing}`;
    }
  }

  // 3. Dynamic patterns (e.g. "Namaste, Ramesh", "Last verified: 2026-11-20", "2 min ago")
  const patternMatch = translatePattern(trimmed, language);
  if (patternMatch) {
    return `${leading}${patternMatch}${trailing}`;
  }

  // 4. Sub-phrase fallback for composite phrases
  if (trimmed.includes(" ")) {
    let result = trimmed;
    for (const [english, hindi, chhattisgarhi] of sortedPhraseEntries) {
      if (english.length >= 4 && result.toLowerCase().includes(english.toLowerCase())) {
        const trans = language === "hi" ? hindi : chhattisgarhi;
        const regex = new RegExp(`\\b${english.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "gi");
        result = result.replace(regex, trans);
      }
    }
    if (result !== trimmed) {
      return `${leading}${result}${trailing}`;
    }
  }

  return source;
}

const reverseDictionary: Record<string, string> = Object.fromEntries(
  entries.flatMap(([english, hindi, chhattisgarhi]: TranslationEntry) => [
    [hindi.toLowerCase().trim(), english],
    [chhattisgarhi.toLowerCase().trim(), english],
  ]),
);

export function getEnglishSource(value: string): string {
  if (!value || !value.trim()) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const trimmed = value.trim();
  const normalized = trimmed.replace(/\s+/g, " ").toLowerCase();

  // 1. Direct reverse dictionary lookup
  const exact = reverseDictionary[normalized];
  if (exact) return `${leading}${exact}${trailing}`;

  // 2. Punctuation stripped reverse lookup
  const { prefix, core, suffix } = stripPunctuation(trimmed);
  if (core && core !== trimmed) {
    const coreKey = core.replace(/\s+/g, " ").trim().toLowerCase();
    const coreExact = reverseDictionary[coreKey];
    if (coreExact) {
      return `${leading}${prefix}${coreExact}${suffix}${trailing}`;
    }
  }

  // 3. Dynamic reverse patterns
  const revNamaste = trimmed.match(/^(?:नमस्ते|जोहार)[,\s]+(.*)$/);
  if (revNamaste) return `${leading}Namaste, ${revNamaste[1].trim()}${trailing}`;

  const revWelcomeBack = trimmed.match(/^(?:वापस स्वागत है|फेर ले स्वागत हे)[,\s]+(.*)$/);
  if (revWelcomeBack) return `${leading}Welcome back, ${revWelcomeBack[1].trim()}${trailing}`;

  const revVerified = trimmed.match(/^(?:अंतिम सत्यापन|आखिरी जांच):\s*(.*)$/);
  if (revVerified) return `${leading}Last verified: ${revVerified[1].trim()}${trailing}`;

  const revMinAgo = trimmed.match(/^(\d+)\s*मिनट\s*(?:पहले|पहिले)$/);
  if (revMinAgo) return `${leading}${revMinAgo[1]} min ago${trailing}`;

  const revUpTo = trimmed.match(/^(₹[\d,]+.*)\s*तक$/);
  if (revUpTo) return `${leading}Up to ${revUpTo[1].trim()}${trailing}`;

  const revYr = trimmed.match(/^(₹[\d,]+)\s*\/\s*(?:वर्ष|साल|बछर)$/);
  if (revYr) return `${leading}${revYr[1]} / yr${trailing}`;

  const revPortal = trimmed.match(/^(.*)\s*पोर्टल$/);
  if (revPortal) {
    const roleKey = revPortal[1].trim().toLowerCase();
    const roleEng = reverseDictionary[roleKey] || revPortal[1].trim();
    return `${leading}${roleEng} Portal${trailing}`;
  }

  const revWorkspace = trimmed.match(/^(.*)\s*(?:कार्यक्षेत्र|काम के जगह)$/);
  if (revWorkspace) {
    const roleKey = revWorkspace[1].trim().toLowerCase();
    const roleEng = reverseDictionary[roleKey] || revWorkspace[1].trim();
    return `${leading}${roleEng} workspace${trailing}`;
  }

  return value;
}
